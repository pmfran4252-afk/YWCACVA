/** Icon keys as stored in the CMS. */
export type BrandIconName =
  | "call"
  | "chat"
  | "direction"
  | "health"
  | "nights"
  | "time"
  | "dress";

export const BRAND_ICONS: Record<
  BrandIconName,
  (props: IconProps) => React.ReactElement
> = {
  call: CallIcon,
  chat: ChatIcon,
  direction: DirectionIcon,
  health: HealthIcon,
  nights: NightsIcon,
  time: TimeIcon,
  dress: DressIcon,
};

export function BrandIcon({
  name,
  className,
}: {
  name?: BrandIconName | null;
  className?: string;
}) {
  if (!name) return null;
  const Icon = BRAND_ICONS[name];
  return Icon ? <Icon className={className} /> : null;
}
